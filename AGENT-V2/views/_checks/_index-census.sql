SELECT 'OB_ORDER' AS TBL,
       COUNT(*) AS IDS_WITH_MULTIPLE_PARENT_KEYS
FROM (SELECT ORDER_ID
      FROM DGSTREAM.OB_ORDER
      GROUP BY ORDER_ID
      HAVING COUNT(DISTINCT ROOT_ID || '~' || PARENT_ID) > 1)
UNION ALL
SELECT 'OB_ORDER_TRADE',
       COUNT(*)
FROM (SELECT ORDER_TRADE_ID
      FROM DGSTREAM.OB_ORDER_TRADE
      GROUP BY ORDER_TRADE_ID
      HAVING COUNT(DISTINCT ROOT_ID) > 1)
UNION ALL
SELECT 'OB_HEDGE_ORDER',
       COUNT(*)
FROM (SELECT HEDGE_ORDER_ID
      FROM DGSTREAM.OB_HEDGE_ORDER
      GROUP BY HEDGE_ORDER_ID
      HAVING COUNT(DISTINCT ROOT_ID) > 1)
UNION ALL
SELECT 'OB_HEDGE_TRADE',
       COUNT(*)
FROM (SELECT HEDGE_TRADE_ID
      FROM DGSTREAM.OB_HEDGE_TRADE
      GROUP BY HEDGE_TRADE_ID
      HAVING COUNT(DISTINCT ROOT_ID) > 1)
UNION ALL
SELECT 'OB_ECM_ORDER',
       COUNT(*)
FROM (SELECT ORDER_ID
      FROM DGSTREAM.OB_ECM_ORDER
      GROUP BY ORDER_ID
      HAVING COUNT(DISTINCT DEAL_ID || '~' || TRANCHE_ID) > 1);
