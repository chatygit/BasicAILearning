SELECT I.TABLE_NAME,
       I.INDEX_NAME,
       I.INDEX_TYPE,
       I.UNIQUENESS,
       I.STATUS,
       LISTAGG(C.COLUMN_NAME, ', ') WITHIN GROUP (ORDER BY C.COLUMN_POSITION) AS INDEX_COLUMNS
FROM ALL_INDEXES I
JOIN ALL_IND_COLUMNS C
  ON C.INDEX_OWNER = I.OWNER
 AND C.INDEX_NAME  = I.INDEX_NAME
 AND C.TABLE_NAME  = I.TABLE_NAME
WHERE I.TABLE_OWNER = 'DGSTREAM'
  AND I.TABLE_NAME IN (
      'OB_ORDER','OB_ORDER_SIZE','OB_ORDER_TRADE','OB_ORDER_TRADE_SYNDICATE',
      'OB_HEDGE_ORDER','OB_HEDGE_TRADE',
      'OB_DEAL_TRANCHE','OB_DEAL_ISSUER','OB_TRANCHE','OB_TRANCHE_RATING',
      'OB_TRANCHE_SYNDICATE_MEMBER',
      'OB_ECM_ORDER','OB_ECM_ORDER_IOI',
      'OB_ECM_TRADE_BOOK_INVESTOR_TRADE','OB_ECM_TRADE_BOOK_DESIGNATION',
      'OPUS_ECM_TRANSACTION','OPUS_ECM_TRANSACTION_STATUS',
      'OPUS_ECM_TRANSACTION_TRANCHE',
      'OPUS_ECM_TRANSACTION_TRANCHE_DEMAND_CURRENCY',
      'OPUS_ECM_TRANSACTION_TRANCHE_PRODUCT_DETAIL',
      'OPUS_ECM_TRANSACTION_TRANCHE_PRODUCT_DETAIL_IDENTIFIER',
      'OPUS_ECM_TRANSACTION_TRANCHE_SYNDICATE',
      'OPUS_BASE_TRANSACTION','OPUS_BASE_TRANSACTION_RELATED_PARTIES')
GROUP BY I.TABLE_NAME, I.INDEX_NAME, I.INDEX_TYPE, I.UNIQUENESS, I.STATUS
ORDER BY I.TABLE_NAME, I.INDEX_NAME;

