SELECT TYPE, COUNT(*) AS ROWS_,
       COUNT(PRICE_DEMAND)  AS HAS_PRICE_LIMIT,
       COUNT(SPREAD_DEMAND) AS HAS_SPREAD_LIMIT,
       COUNT(MIN_YIELD)     AS HAS_MIN_YIELD,
