-- ===========================================================================
-- N2. 2026-09-21 — IPREO BUILD, LAST CHECKS. The mirror tables
-- (IPREO_OPUS_ECM_* / IPREO_OB_ECM_ORDER*) are the spine; these settle the
-- keys between mirror and raw tables, the mirror vocabularies, and which raw
-- columns can fill the gaps (issuer name, tranche name/size, currency, fees,
-- investor type/region, billed-by). Ten statements, one run.
-- ===========================================================================

-- N2-1. Mirror-to-mirror keys (the joins the branch will use).
SELECT (SELECT COUNT(*) FROM DGSTREAM.IPREO_OB_ECM_ORDER O
         WHERE EXISTS (SELECT 1 FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION T
                       WHERE T.DEAL_TRANSACTION_ID = O.DEAL_ID)) AS ORDERS_WITH_DEAL_,
       (SELECT COUNT(*) FROM DGSTREAM.IPREO_OB_ECM_ORDER O
         WHERE EXISTS (SELECT 1 FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION_TRANCHE T
                       WHERE TO_CHAR(T.ECM_TRANSACTION_TRANCHE_ID) = O.TRANCHE_ID)) AS ORDERS_WITH_TRANCHE_,
       (SELECT COUNT(*) FROM DGSTREAM.IPREO_OB_ECM_ORDER O
         WHERE EXISTS (SELECT 1 FROM DGSTREAM.IPREO_OB_ECM_ORDER_IOI I WHERE I.ORDER_ID = O.ORDER_ID)) AS ORDERS_WITH_IOI_,
       (SELECT COUNT(*) FROM DGSTREAM.IPREO_OB_ECM_ORDER) AS ORDERS_
FROM   DUAL;

-- N2-2. Mirror-to-raw keys (enable enrichment from the raw tables).
SELECT (SELECT COUNT(*) FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION T
         WHERE EXISTS (SELECT 1 FROM DGSTREAM.IPREO_ISSUE I WHERE TO_CHAR(I.ISS_ID) = T.DEAL_TRANSACTION_ID)) AS TXNS_MATCHING_ISSUE_,
       (SELECT COUNT(*) FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION_TRANCHE T
         WHERE EXISTS (SELECT 1 FROM DGSTREAM.IPREO_TRANCHE R WHERE R.TRN_ID = T.ECM_TRANSACTION_TRANCHE_ID)) AS TRANCHES_MATCHING_RAW_,
       (SELECT COUNT(*) FROM DGSTREAM.IPREO_OB_ECM_ORDER O
         WHERE EXISTS (SELECT 1 FROM DGSTREAM.IPREO_ORDER R WHERE TO_CHAR(R.ORD_ID) = O.ORDER_ID)) AS ORDERS_MATCHING_RAW_
FROM   DUAL;

-- N2-3. Mirror order vocabularies (the exclusion + unit + type mapping).
SELECT 'ORDER_STATUS' AS COL, ORDER_STATUS AS VAL, COUNT(*) AS N FROM DGSTREAM.IPREO_OB_ECM_ORDER GROUP BY ORDER_STATUS
UNION ALL SELECT 'IOI_UNIT', IOI_UNIT, COUNT(*) FROM DGSTREAM.IPREO_OB_ECM_ORDER GROUP BY IOI_UNIT
UNION ALL SELECT 'IOI_TYPE', IOI_TYPE, COUNT(*) FROM DGSTREAM.IPREO_OB_ECM_ORDER GROUP BY IOI_TYPE
UNION ALL SELECT 'IOI.LIMIT_TYPE', LIMIT_TYPE, COUNT(*) FROM DGSTREAM.IPREO_OB_ECM_ORDER_IOI GROUP BY LIMIT_TYPE
ORDER  BY 1, 3 DESC;

-- N2-4. Mirror order fill.
SELECT COUNT(*) AS ORDERS_, COUNT(INVESTOR_GPNUM) AS HAS_GPNUM_, COUNT(INVESTOR_NAME) AS HAS_NAME_,
       SUM(CASE WHEN PRIVATE_ALLOC > 0 THEN 1 ELSE 0 END) AS ALLOC_GT0_,
       COUNT(INST_ALLOCATION_QTY) AS HAS_INST_ALLOC_, COUNT(INVESTOR_SALESPERSON_NAME) AS HAS_SALES_,
       COUNT(DISTINCT DEAL_ID) AS DEALS_, COUNT(DISTINCT TRANCHE_ID) AS TRANCHES_
FROM   DGSTREAM.IPREO_OB_ECM_ORDER;

-- N2-5. Issuer name candidates: what IPREO_ISSUE calls the deal, beside the
--       mirror's deal name; and whether the OPUS_BASE party master / base
--       transaction know the Ipreo ids at all.
SELECT * FROM (
  SELECT I.ISS_ID, I.ISSUE_NM, I.ISSUE_TYPE_NM, I.EXT_ISS_CD, T.SYNDICATE_DEAL_NAME
  FROM   DGSTREAM.IPREO_ISSUE I
  JOIN   DGSTREAM.IPREO_OPUS_ECM_TRANSACTION T ON T.DEAL_TRANSACTION_ID = TO_CHAR(I.ISS_ID)
  ORDER  BY I.PRICING_DT DESC NULLS LAST) WHERE ROWNUM <= 10;

SELECT (SELECT COUNT(DISTINCT T.DEAL_TRANSACTION_ID) FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION T
         WHERE EXISTS (SELECT 1 FROM DGSTREAM.OPUS_BASE_TRANSACTION_RELATED_PARTIES P
                       WHERE P.TRANSACTION_ID = T.DEAL_TRANSACTION_ID AND P.PARTY_ROLE = 'Primary Client')) AS TXNS_IN_PARTY_MASTER_,
       (SELECT COUNT(DISTINCT T.DEAL_TRANSACTION_ID) FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION T
         WHERE EXISTS (SELECT 1 FROM DGSTREAM.OPUS_BASE_TRANSACTION B WHERE B.TRANSACTION_ID = T.DEAL_TRANSACTION_ID)) AS TXNS_IN_BASE_TXN_
FROM   DUAL;

-- N2-6. Currency sources (the mirror's CURRENCY_CODE is 1.8 % filled).
SELECT 'ISSUE.CCY_CD' AS COL, CCY_CD AS VAL, COUNT(*) AS N FROM DGSTREAM.IPREO_ISSUE GROUP BY CCY_CD
UNION ALL SELECT 'PRODUCT.PRD_CCY_CD', PRD_CCY_CD, COUNT(*) FROM DGSTREAM.IPREO_PRODUCT GROUP BY PRD_CCY_CD
UNION ALL SELECT 'PRODUCT.SEC_TYPE_CD', SEC_TYPE_CD, COUNT(*) FROM DGSTREAM.IPREO_PRODUCT GROUP BY SEC_TYPE_CD
ORDER  BY 1, 3 DESC;

-- N2-7. Raw tranche attributes: fill + status vocabulary + 5 sample rows.
SELECT COUNT(*) AS TRANCHES_, COUNT(TRN_NM) AS HAS_NAME_, COUNT(ACTIVE_TRANCHE_SIZE_QTY) AS HAS_ACTIVE_SIZE_,
       COUNT(TRN_UN_SIZE_QTY) AS HAS_UN_SIZE_, COUNT(OVERALLOTMENT_QTY) AS HAS_GREENSHOE_, COUNT(STATUS) AS HAS_STATUS_
FROM   DGSTREAM.IPREO_TRANCHE;
SELECT STATUS, COUNT(*) AS N FROM DGSTREAM.IPREO_TRANCHE GROUP BY STATUS ORDER BY N DESC;
SELECT * FROM (SELECT TRN_ID, ISS_ID, TRN_NM, TRN_NM_CD, ACTIVE_TRANCHE_SIZE_QTY, TRN_UN_SIZE_QTY, STATUS, OVERALLOTMENT_QTY
               FROM DGSTREAM.IPREO_TRANCHE ORDER BY TIME_STAMP DESC NULLS LAST) WHERE ROWNUM <= 5;

-- N2-8. Product detail + syndicate vocabularies (tranche product type, price,
--       roles), and the order-level billed-by broker.
SELECT 'PD.EQUITY_TYPE' AS COL, EQUITY_TYPE AS VAL, COUNT(*) AS N FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION_TRANCHE_PRODUCT_DETAIL GROUP BY EQUITY_TYPE
UNION ALL SELECT 'PD.FINAL_PRICE filled', CASE WHEN FINAL_PRICE IS NULL THEN 'NULL' ELSE 'FILLED' END, COUNT(*) FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION_TRANCHE_PRODUCT_DETAIL GROUP BY CASE WHEN FINAL_PRICE IS NULL THEN 'NULL' ELSE 'FILLED' END
UNION ALL SELECT 'SYN.SYNDICATE_ROLE', SYNDICATE_ROLE, COUNT(*) FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION_TRANCHE_SYNDICATE GROUP BY SYNDICATE_ROLE
UNION ALL SELECT 'SYN.BROKER_CODE filled', CASE WHEN BROKER_CODE IS NULL THEN 'NULL' ELSE 'FILLED' END, COUNT(*) FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION_TRANCHE_SYNDICATE GROUP BY CASE WHEN BROKER_CODE IS NULL THEN 'NULL' ELSE 'FILLED' END
UNION ALL SELECT 'ORDER.BILLED_BY_BRK_CD', BILLED_BY_BRK_CD, COUNT(*) FROM DGSTREAM.IPREO_ORDER GROUP BY BILLED_BY_BRK_CD
ORDER  BY 1, 3 DESC;

-- N2-9. Fees and prices from the raw product tables (keyed by ISS_ID / PRD_ID).
SELECT COUNT(*) AS FEE_ROWS_, COUNT(DISTINCT ISS_ID) AS ISSUES_WITH_FEES_, COUNT(GROSS_SPREAD_AMT) AS HAS_GROSS_,
       COUNT(U_W_FEE_AMT) AS HAS_UW_, COUNT(MGMT_FEE_AMT) AS HAS_MGMT_, COUNT(SELLING_CONC_FEE_AMT) AS HAS_SELL_
FROM   DGSTREAM.IPREO_PRODUCTFEE;
SELECT COUNT(*) AS PRODUCTS_, COUNT(DISTINCT ISS_ID) AS ISSUES_, COUNT(OFFER_PX) AS HAS_OFFER_PX_,
       COUNT(PAR_VALUE) AS HAS_PAR_, COUNT(FILE_PX) AS HAS_FILE_PX_, COUNT(INIT_FILE_PX_LO) AS HAS_RANGE_
FROM   DGSTREAM.IPREO_PRODUCT;

-- N2-10. Raw order enrichment: investor type / country vocabularies and the
--        timestamps (book momentum) — fill only.
SELECT 'INV_TYPE_NM' AS COL, INV_TYPE_NM AS VAL, COUNT(*) AS N FROM DGSTREAM.IPREO_ORDER GROUP BY INV_TYPE_NM
UNION ALL SELECT 'CNTRY_CODE', CNTRY_CODE, COUNT(*) FROM DGSTREAM.IPREO_ORDER GROUP BY CNTRY_CODE
ORDER  BY 1, 3 DESC FETCH FIRST 40 ROWS ONLY;
SELECT COUNT(*) AS ORDERS_, COUNT(CREATE_DT) AS HAS_CREATE_TS_, COUNT(LAST_DEMAND_MODIFIED_DT) AS HAS_DEMAND_TS_,
       COUNT(LAST_ALLOC_MODIFIED_DTTM) AS HAS_ALLOC_TS_, COUNT(AE_UP_LAST_NM) AS HAS_SALES_NM_,
       COUNT(SETTLEMENT_CCY_CD) AS HAS_SETTLE_CCY_
FROM   DGSTREAM.IPREO_ORDER;
