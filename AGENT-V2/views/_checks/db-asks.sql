-- N7-5. FEE JOIN, before wiring: the tranche's product id column (name from
--       the DDL screenshot, never run) and whether one tranche maps to one fee
--       row. Both must hold: no ORA-00904, and MULTI_ = 0.
SELECT DEFAULT_PRD_ID FROM DGSTREAM.IPREO_TRANCHE WHERE 1 = 0;
SELECT COUNT(*) AS TRANCHES_, COUNT(T.DEFAULT_PRD_ID) AS HAS_PRD_,
       SUM(CASE WHEN F.N > 1 THEN 1 ELSE 0 END) AS MULTI_, SUM(CASE WHEN F.N = 1 THEN 1 ELSE 0 END) AS ONE_
FROM   DGSTREAM.IPREO_TRANCHE T
LEFT JOIN (SELECT PRD_ID, COUNT(*) AS N FROM DGSTREAM.IPREO_PRODUCTFEE GROUP BY PRD_ID) F
       ON F.PRD_ID = T.DEFAULT_PRD_ID;
