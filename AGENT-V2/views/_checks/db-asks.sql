-- N7-1. ALLOCATION SEMANTICS on Visa. The view's TOTAL_ALLOCATION is
--       1,009,616,809 on a 406,000,000-share deal (2.5x — impossible for a
--       final share allocation) and seven of the top ten orders carry exactly
--       19,000,000. Which column sums to <= 446,600,000 (deal + 10 % shoe)?
SELECT COUNT(*) AS ORDERS_, COUNT(DISTINCT INVESTOR_NAME) AS INVESTORS_,
       SUM(PRIVATE_ALLOC) AS SUM_PRIVATE_ALLOC_, SUM(INST_ALLOCATION_QTY) AS SUM_INST_ALLOC_QTY_,
       COUNT(PRIVATE_ALLOC) AS HAS_PRIVATE_, COUNT(INST_ALLOCATION_QTY) AS HAS_INST_,
       MAX(PRIVATE_ALLOC) AS MAX_PRIVATE_, MAX(INST_ALLOCATION_QTY) AS MAX_INST_
FROM   DGSTREAM.IPREO_OB_ECM_ORDER
WHERE  DEAL_ID = '1447528575'
AND    (ORDER_STATUS IS NULL OR ORDER_STATUS NOT IN ('CANCELLED', 'DELETED', 'PASS'));
SELECT INVESTOR_NAME, ORDER_ID, PRIVATE_ALLOC, INST_ALLOCATION_QTY, INST_RETENTION_QTY, ORDER_STATUS
FROM   DGSTREAM.IPREO_OB_ECM_ORDER
WHERE  DEAL_ID = '1447528575' AND (UPPER(INVESTOR_NAME) LIKE 'FIDELITY%' OR UPPER(INVESTOR_NAME) LIKE 'KUWAIT%' OR UPPER(INVESTOR_NAME) LIKE 'KIA %')
ORDER  BY PRIVATE_ALLOC DESC;
SELECT COUNT(*) AS RAW_ORDERS_, SUM(INST_ALLOC_QTY) AS SUM_INST_ALLOC_QTY_, SUM(INST_ALLOC_SIZE) AS SUM_INST_ALLOC_SIZE_,
       SUM(RET_ALLOC_QTY) AS SUM_RET_ALLOC_QTY_, SUM(RET_ALLOC_SIZE) AS SUM_RET_ALLOC_SIZE_
FROM   DGSTREAM.IPREO_ORDER
WHERE  ISS_ID = 1447528575;

-- N7-2. CURRENCY-ORDER DEMAND. The mirror's IOI_QTY on Visa's currency orders
--       reads as money / 44.00 (340,909.0909 = 15,000,000 / 44; Visa priced at
--       44) — i.e. already a share-equivalent, which the views now use (repo:
--       ORDER_DEMAND_QTY and TOTAL_DEMAND include CURRENCY; DEMAND_AS_SUBMITTED
--       takes the raw money amount). Confirm on five rows.
SELECT O.INVESTOR_NAME, O.IOI_UNIT, M.IOI_QTY AS MIRROR_QTY_, R.IOI_QTY AS RAW_QTY_, R.IOI_AMT AS RAW_AMT_,
       R.IOI_AMT_TYPE, P.OFFER_PX
FROM   DGSTREAM.IPREO_OB_ECM_ORDER O
LEFT JOIN DGSTREAM.IPREO_OB_ECM_ORDER_IOI M ON M.ORDER_ID = O.ORDER_ID
LEFT JOIN DGSTREAM.IPREO_ORDERIOI R ON R.ORD_ID = TO_NUMBER(O.ORDER_ID DEFAULT NULL ON CONVERSION ERROR)
LEFT JOIN DGSTREAM.IPREO_PRODUCT P ON P.ISS_ID = 1447528575
WHERE  O.DEAL_ID = '1447528575' AND O.IOI_UNIT = 'CURRENCY' AND ROWNUM <= 5;
SELECT IOI_UNIT, COUNT(*) AS ORDERS_ FROM DGSTREAM.IPREO_OB_ECM_ORDER GROUP BY IOI_UNIT ORDER BY 2 DESC;

