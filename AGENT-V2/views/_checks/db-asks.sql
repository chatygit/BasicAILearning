       COUNT(MIN_SIZE)      AS HAS_MIN_SIZE,
       COUNT(CREATED_TS)    AS HAS_CREATED_TS
FROM   DGSTREAM.OB_ORDER_SIZE
GROUP  BY TYPE
ORDER  BY ROWS_ DESC;

