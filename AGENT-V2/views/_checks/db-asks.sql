-- S2. STANDING — SCALE RE-CENSUS FOR A NEW ENVIRONMENT (PROD at promote time,
-- run by the access holder). Counts > 0 in a _GT4/_GT6/_GT9 column mean a
-- value carries more decimals than the view's ROUND bound and would be
-- rounded on read; DEV/UAT counts are not expectations.
-- ===========================================================================
SELECT 'OB_ORDER_SIZE.AMT' AS COL,
       COUNT(AMT) AS NONNULL_,
       COUNT(CASE WHEN AMT <> ROUND(AMT, 4) THEN 1 END) AS SCALE_GT4,
       COUNT(CASE WHEN AMT <> ROUND(AMT, 9) THEN 1 END) AS SCALE_GT9,
       MAX(CASE WHEN AMT <> ROUND(AMT, 4) THEN AMT END) AS SAMPLE_GT4
FROM DGSTREAM.OB_ORDER_SIZE;

SELECT COUNT(FINAL_ALLOC) AS ALLOC_NONNULL,
       COUNT(CASE WHEN FINAL_ALLOC <> ROUND(FINAL_ALLOC, 4) THEN 1 END) AS ALLOC_GT4,
       COUNT(CASE WHEN FINAL_ALLOC <> ROUND(FINAL_ALLOC, 9) THEN 1 END) AS ALLOC_GT9,
       COUNT(CASE WHEN ORDER_SIZE_CHANGE <> ROUND(ORDER_SIZE_CHANGE, 4) THEN 1 END) AS SIZECHG_GT4
FROM DGSTREAM.OB_ORDER;

