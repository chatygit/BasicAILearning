CREATE OR REPLACE VIEW "DGSTREAM"."VW_ORDER_DETAIL" AS
SELECT
    'ECM' AS PRODUCT,
    O.DEAL_ID AS DEAL_ID,
    T.SYNDICATE_DEAL_NAME AS DEAL_NAME,
    O.TRANCHE_ID AS TRANCHE_ID,
    TT.TRANCHE_NAME AS TRANCHE_NAME,
    O.ORDER_ID AS ORDER_ID,
    O.INVESTOR_NAME AS INVESTOR_NAME,
    O.INVESTOR_GPNUM AS INVESTOR_GP_ID,
    O.INVESTOR_REGION AS INVESTOR_REGION,
    O.INVESTOR_CATEGORY_KEY AS INVESTOR_CATEGORY_KEY,
    O.INVESTOR_CATEGORY_VALUE AS INVESTOR_CATEGORY,
    O.MEETING_TYPE_KEY AS MEETING_TYPE_KEY,
    O.MEETING_TYPE_VALUE AS MEETING_TYPE,
    O.ORDER_TYPE AS ORDER_TYPE,
    O.IOI_TYPE AS IOI_TYPE,
    CAST(NVL(LM.LIMIT_VALUE, 0) AS NUMBER(38,4)) AS ORDER_AMOUNT,
    CAST(NVL(O.DEMAND_QTY,
             CASE WHEN O.IOI_UNIT IN ('SHARES', 'BOND') THEN OI.IOI_QTY END)
         AS NUMBER(38,4)) AS ORDER_DEMAND_QTY,
    O.IOI_UNIT AS DEMAND_UNIT,
    CAST(OI.IOI_QTY AS NUMBER(38,4)) AS DEMAND_AS_SUBMITTED,
    CAST(O.PRIVATE_ALLOC AS NUMBER(38,4)) AS ORDER_ALLOCATION,
    CAST(TT.PRICING_TS AS TIMESTAMP(3)) AS PRICING_TS,
    NVL(TDC.CURRENCY_NAME, GC.CURRENCY_NAME) AS CURRENCY,
    NVL(PCM.PARTY_NAME, NVL(OIN.ISSUER_NAME_BY_GFCID, T.ISSUER_NAME_FROM_SOURCE)) AS ISSUER_NAME,
    T.ISSUER_INDUSTRY_SECTOR AS SECTOR,
    CAST(CASE WHEN TT.TRANCHE_OFFER_SIZE IS NULL THEN 0
         WHEN REGEXP_LIKE(TO_CHAR(TT.TRANCHE_OFFER_SIZE),
                          '^\s*[+-]?[0-9]+(\.[0-9]+)?([Ee][+-]?[0-9]+)?\s*$')
         THEN TO_NUMBER(TRIM(TO_CHAR(TT.TRANCHE_OFFER_SIZE)))
         ELSE NULL END AS NUMBER(38,4)) AS TRANCHE_SIZE,
    O.BILLEDBY_BROKER_CODE AS BILLED_BY,
    T.PRODUCT_OFFERING_TYPE_VALUE AS OFFERING_TYPE,
    T.PRODUCT_EQUITY_TYPE_VALUE AS EQUITY_TYPE,
    CASE WHEN O.IS_OWNED = 'true' THEN 'HOME'
         WHEN O.IS_OWNED = 'false' THEN 'AWAY'
         ELSE NULL END AS ORDER_OWNERSHIP,
    O.DEAL_ID AS TRANSACTION_ID,
    O.INVESTOR_SALESPERSON_NAME AS SALES_PERSON,
    O.INVESTOR_LEID AS INVESTOR_LEI,
    O.ORDER_STATUS AS ORDER_STATUS,
    CAST(NULL AS VARCHAR2(400)) AS INVESTOR_QIB_STATUS,
    CAST(NULL AS VARCHAR2(500)) AS INVESTOR_SUB_TYPE,
    O.IS_FIRM_ORDER AS IS_FIRM_ORDER,
    O.IS_POT_ORDER AS IS_POT,
    TO_CHAR(O.DRAFT_ALLOC) AS DRAFT_ALLOC,
    CAST(NULL AS VARCHAR2(400)) AS SOFT_ALLOC,
    CAST(NULL AS VARCHAR2(400)) AS ISN_ALLOC,
    CAST(NULL AS VARCHAR2(400)) AS RETENTION,
    CAST(NULL AS VARCHAR2(4000)) AS RATIONALE,
    CAST(NULL AS VARCHAR2(400)) AS RATIONALE_TYPE,
    CAST(NULL AS VARCHAR2(400)) AS FX_CURRENCY,
    CAST(NULL AS VARCHAR2(500)) AS OBO_NAME,
    CAST(NULL AS VARCHAR2(400)) AS OBO_LEGAL_ENTITY_ID,
    CAST(NULL AS VARCHAR2(400)) AS ESG_TAG,
    CAST(NULL AS NUMBER(38,4)) AS ORDER_SIZE_CHANGE,
    CAST(NULL AS VARCHAR2(400)) AS IS_AFFILIATED,
    CAST(NULL AS VARCHAR2(400)) AS ONE_OFF_INVESTOR,
    O.INVESTOR_SALESPERSON_SOEID AS SALES_SOEID,
    O.WALL_CROSSED_VALUE AS WALL_CROSSED,
    O.INVESTOR_CLASSIFICATION_VALUE AS INVESTOR_CLASSIFICATION,
    O.EXISTING_HOLDER_VALUE AS EXISTING_HOLDER,
    CAST(O.ACTIVE_PRICE AS NUMBER(38,6)) AS ACTIVE_PRICE,
    O.BOOK_STATUS AS BOOK_STATUS,
    OBT.DEAL_REGION AS DEAL_REGION,
    CAST(NULL AS VARCHAR2(1000)) AS TRANCHE_REGION,
    S.STATUS_VALUE AS DEAL_STATUS,
    CAST(T.DEAL_SIZE AS NUMBER(38,4)) AS DEAL_SIZE,
    T.USE_OF_PROCEEDS AS USE_OF_PROCEEDS,
    CAST(NULL AS TIMESTAMP(6)) AS SETTLEMENT_TS,
    CAST(NULL AS VARCHAR2(4000)) AS TENORS,
    CAST(NULL AS VARCHAR2(4000)) AS PRODUCT_CLASS,
    T.PRODUCT_EQUITY_CLASS_VALUE AS DEAL_CLASS,
    LM.LIMIT_TYPE AS LIMIT_TYPE,
    CAST(LM.LIMIT_VALUE AS NUMBER(38,6)) AS LIMIT_VALUE,
    CAST(LM.LIMIT_COUPON AS NUMBER(38,6)) AS LIMIT_COUPON,
    CAST(LM.LIMIT_PREMIUM AS NUMBER(38,6)) AS LIMIT_PREMIUM,
    LM.LIMIT_CURRENCY AS LIMIT_CURRENCY,
    CASE WHEN LV.IOI_LEVELS IS NOT NULL
         THEN CASE UPPER(O.IOI_UNIT) WHEN 'CURRENCY' THEN 'amounts: '
                                     WHEN 'PERCENT' THEN '% of deal: '
                                     WHEN 'FACE' THEN 'face: '
                                     ELSE '' END || LV.IOI_LEVELS END AS IOI_LEVELS,
    O.SOURCE AS ORDER_SOURCE,
    CAST(CASE WHEN UPPER(O.IOI_UNIT) = 'CURRENCY' THEN OI.IOI_QTY
              WHEN UPPER(O.IOI_UNIT) = 'SHARES' AND LM.LIMIT_VALUE IS NOT NULL
                   AND NVL(UPPER(LM.LIMIT_CURRENCY), 'USD') = 'USD'
              THEN LM.IOI_QTY * LM.LIMIT_VALUE END AS NUMBER(38,4)) AS INDICATION_USD
FROM (
    SELECT E.*
    FROM (
        SELECT EO.*,
               ROW_NUMBER() OVER (PARTITION BY EO.DEAL_ID, EO.TRANCHE_ID, EO.ORDER_ID
                                  ORDER BY EO.ROWID) AS RN_
        FROM DGSTREAM.OB_ECM_ORDER EO
        WHERE EO.ORDER_ID IS NOT NULL
    ) E
    WHERE E.RN_ = 1
) O
INNER JOIN (
    SELECT X.*
    FROM (
        SELECT Y.*,
               ROW_NUMBER() OVER (PARTITION BY Y.DEAL_TRANSACTION_ID
                                  ORDER BY Y.HAS_TRANCHE_ DESC, Y.ECM_TRANSACTION_ID DESC, Y.ROW_ID_) AS RN_
        FROM (
            SELECT ET.ECM_TRANSACTION_ID, ET.DEAL_TRANSACTION_ID,
                   ET.SYNDICATE_DEAL_NAME, ET.ISSUER_NAME_FROM_SOURCE,
                   ET.ISSUER_INDUSTRY_SECTOR, ET.PRODUCT_OFFERING_TYPE_VALUE,
                   ET.PRODUCT_EQUITY_TYPE_VALUE, ET.DEAL_SIZE,
                   ET.USE_OF_PROCEEDS,
                   ET.ISSUER_GFCID, ET.PRODUCT_EQUITY_CLASS_VALUE,
                   ROWIDTOCHAR(ET.ROWID) AS ROW_ID_,
                   CASE WHEN TX.ECM_TRANSACTION_ID IS NOT NULL THEN 1 ELSE 0 END AS HAS_TRANCHE_
            FROM DGSTREAM.OPUS_ECM_TRANSACTION ET
            LEFT JOIN (SELECT DISTINCT ECM_TRANSACTION_ID
                       FROM DGSTREAM.OPUS_ECM_TRANSACTION_TRANCHE) TX
              ON TX.ECM_TRANSACTION_ID = ET.ECM_TRANSACTION_ID
            WHERE EXISTS (SELECT 1 FROM DGSTREAM.OPUS_ECM_TRANSACTION_STATUS ST
                          WHERE ST.ECM_TRANSACTION_ID = ET.ECM_TRANSACTION_ID
                            AND ST.STATUS_TYPE = 'Execution_Status'
                            AND ST.STATUS_VALUE NOT IN ('Confidential', 'Withdrawn', 'Terminated'))
        ) Y
    ) X
    WHERE X.RN_ = 1
) T
    ON O.DEAL_ID = T.DEAL_TRANSACTION_ID
    AND O.ORDER_STATUS NOT IN ('CANCELLED', 'DELETED', 'PASS')
    AND ((O.IS_MATCHED = 'true' AND O.IS_DOMINANT = 'true') OR O.IS_MATCHED = 'false')
INNER JOIN (
    SELECT ECM_TRANSACTION_ID,
           MAX(STATUS_VALUE) AS STATUS_VALUE
    FROM DGSTREAM.OPUS_ECM_TRANSACTION_STATUS
    WHERE STATUS_TYPE = 'Execution_Status'
      AND STATUS_VALUE NOT IN ('Confidential', 'Withdrawn', 'Terminated')
    GROUP BY ECM_TRANSACTION_ID
) S
    ON T.ECM_TRANSACTION_ID = S.ECM_TRANSACTION_ID
LEFT JOIN (
    SELECT ORDER_ID, MAX(LIMIT_VALUE) AS LIMIT_VALUE,
           MAX(IOI_QTY) AS IOI_QTY
    FROM DGSTREAM.OB_ECM_ORDER_IOI
    GROUP BY ORDER_ID
) OI
    ON O.ORDER_ID = OI.ORDER_ID
LEFT JOIN (
    SELECT L.ORDER_ID, L.IOI_QTY, L.LIMIT_TYPE, L.LIMIT_VALUE, L.LIMIT_COUPON, L.LIMIT_PREMIUM, L.LIMIT_CURRENCY
    FROM (
        SELECT I.ORDER_ID, I.IOI_QTY, I.LIMIT_TYPE, I.LIMIT_VALUE, I.LIMIT_COUPON, I.LIMIT_PREMIUM, I.LIMIT_CURRENCY,
               ROW_NUMBER() OVER (PARTITION BY I.ORDER_ID
                                  ORDER BY I.IOI_QTY DESC NULLS LAST, I.ROWID) AS RN_
        FROM DGSTREAM.OB_ECM_ORDER_IOI I
    ) L
    WHERE L.RN_ = 1
) LM
    ON LM.ORDER_ID = O.ORDER_ID
LEFT JOIN (
    SELECT V.ORDER_ID,
           CASE WHEN COUNT(*) > 1 THEN
             LISTAGG(RTRIM(TO_CHAR(V.IOI_QTY, 'FM999,999,999,999,999,999,990.9999'), '.') ||
                     CASE WHEN V.LIMIT_VALUE IS NOT NULL
                          THEN ' @ ' || TRIM(TO_CHAR(V.LIMIT_VALUE, '999,999,999,999,999,990.00'))
                          WHEN V.LIMIT_COUPON IS NOT NULL OR V.LIMIT_PREMIUM IS NOT NULL
                          THEN ' @ coupon ' || TRIM(TO_CHAR(V.LIMIT_COUPON, '990.0999')) ||
                               '% / premium ' || TRIM(TO_CHAR(V.LIMIT_PREMIUM, '990.0999')) || '%'
                          ELSE ' @ market' END,
                     ' | ' ON OVERFLOW TRUNCATE '...' WITH COUNT)
               WITHIN GROUP (ORDER BY CASE WHEN V.LIMIT_VALUE IS NULL AND V.LIMIT_COUPON IS NULL
                                            AND V.LIMIT_PREMIUM IS NULL THEN 0 ELSE 1 END,
                                       V.LIMIT_VALUE DESC NULLS LAST, V.IOI_QTY)
           END AS IOI_LEVELS
    FROM (
        SELECT DISTINCT I.ORDER_ID, I.IOI_QTY, I.LIMIT_VALUE, I.LIMIT_COUPON, I.LIMIT_PREMIUM
        FROM DGSTREAM.OB_ECM_ORDER_IOI I
        WHERE I.IOI_QTY IS NOT NULL
    ) V
    GROUP BY V.ORDER_ID
) LV
    ON LV.ORDER_ID = O.ORDER_ID
LEFT JOIN (
    SELECT W.*
    FROM (
        SELECT TTR.ECM_TRANSACTION_ID, TTR.ECM_TRANSACTION_TRANCHE_ID,
               TTR.TRANCHE_NAME, TTR.PRICING_TS, TTR.TRANCHE_CURRENCY_ID,
               TTR.TRANCHE_OFFER_SIZE,
               ROW_NUMBER() OVER (PARTITION BY TTR.ECM_TRANSACTION_TRANCHE_ID
                                  ORDER BY TTR.ECM_TRANSACTION_ID DESC, TTR.ROWID) AS RN_
        FROM DGSTREAM.OPUS_ECM_TRANSACTION_TRANCHE TTR
    ) W
    WHERE W.RN_ = 1
) TT
    ON TO_CHAR(TT.ECM_TRANSACTION_TRANCHE_ID) = O.TRANCHE_ID
LEFT JOIN (
    SELECT ECM_TRANSACTION_ID, ECM_TRANSACTION_TRANCHE_ID, CURRENCY_ID,
           MAX(CURRENCY_NAME) AS CURRENCY_NAME
    FROM DGSTREAM.OPUS_ECM_TRANSACTION_TRANCHE_DEMAND_CURRENCY
    GROUP BY ECM_TRANSACTION_ID, ECM_TRANSACTION_TRANCHE_ID, CURRENCY_ID
) TDC
    ON TT.ECM_TRANSACTION_ID = TDC.ECM_TRANSACTION_ID
    AND TT.ECM_TRANSACTION_TRANCHE_ID = TDC.ECM_TRANSACTION_TRANCHE_ID
    AND TT.TRANCHE_CURRENCY_ID = TDC.CURRENCY_ID
LEFT JOIN (
    SELECT CURRENCY_ID, MAX(CURRENCY_NAME) AS CURRENCY_NAME
    FROM DGSTREAM.OPUS_ECM_TRANSACTION_TRANCHE_DEMAND_CURRENCY
    GROUP BY CURRENCY_ID
) GC
    ON GC.CURRENCY_ID = TT.TRANCHE_CURRENCY_ID

LEFT JOIN (
    SELECT GFCID, MAX(NAME) AS ISSUER_NAME_BY_GFCID
    FROM DGSTREAM.OB_DEAL_ISSUER
    WHERE GFCID IS NOT NULL AND NAME IS NOT NULL
    GROUP BY GFCID
) OIN
    ON OIN.GFCID = T.ISSUER_GFCID
LEFT JOIN (
    SELECT B.TRANSACTION_ID, B.DEAL_REGION
    FROM (
        SELECT OB.TRANSACTION_ID, OB.DEAL_REGION,
               ROW_NUMBER() OVER (PARTITION BY OB.TRANSACTION_ID
                                  ORDER BY OB.VERSION DESC NULLS LAST, OB.PUBLISHED_TS DESC, OB.ROWID) AS RN_
        FROM DGSTREAM.OPUS_BASE_TRANSACTION OB
    ) B
    WHERE B.RN_ = 1
) OBT
    ON OBT.TRANSACTION_ID = T.DEAL_TRANSACTION_ID

LEFT JOIN (
    SELECT TRANSACTION_ID, PARTY_NAME, PARTY_GFCID, PARTY_TICKER
    FROM (
        SELECT TRANSACTION_ID, PARTY_NAME, PARTY_GFCID, PARTY_TICKER,
               ROW_NUMBER() OVER (PARTITION BY TRANSACTION_ID
                                  ORDER BY PUBLISHED_TS DESC) AS RN_
        FROM DGSTREAM.OPUS_BASE_TRANSACTION_RELATED_PARTIES
        WHERE PARTY_ROLE = 'Primary Client'
    ) WHERE RN_ = 1
) PCM
    ON PCM.TRANSACTION_ID = T.DEAL_TRANSACTION_ID

UNION ALL

SELECT
    'ECM' AS PRODUCT,
    O.DEAL_ID AS DEAL_ID,
    T.SYNDICATE_DEAL_NAME AS DEAL_NAME,
    O.TRANCHE_ID AS TRANCHE_ID,
    RT.TRN_NM AS TRANCHE_NAME,
    O.ORDER_ID AS ORDER_ID,
    NVL(CN.INVESTOR_NAME, O.INVESTOR_NAME) AS INVESTOR_NAME,
    O.INVESTOR_GPNUM AS INVESTOR_GP_ID,
    RO.CNTRY_CODE AS INVESTOR_REGION,
    CAST(NULL AS VARCHAR2(1020)) AS INVESTOR_CATEGORY_KEY,
    RO.INV_TYPE_NM AS INVESTOR_CATEGORY,
    CAST(NULL AS VARCHAR2(1020)) AS MEETING_TYPE_KEY,
    CAST(NULL AS VARCHAR2(1020)) AS MEETING_TYPE,
    CAST(NULL AS VARCHAR2(1020)) AS ORDER_TYPE,
    O.IOI_TYPE AS IOI_TYPE,
    CAST(NVL(LM.LIMIT_VALUE, 0) AS NUMBER(38,4)) AS ORDER_AMOUNT,
    CAST(ROUND(NULLIF(OI.IOI_QTY, 0)) AS NUMBER(38,4)) AS ORDER_DEMAND_QTY,
    O.IOI_UNIT AS DEMAND_UNIT,
    CAST(CASE WHEN O.IOI_UNIT IN ('CURRENCY', 'FACE')
              THEN NULLIF((SELECT MAX(R.IOI_AMT) FROM DGSTREAM.IPREO_ORDERIOI R
                           WHERE R.ORD_ID = TO_NUMBER(O.ORDER_ID DEFAULT NULL ON CONVERSION ERROR)), 0)
              ELSE NULLIF(OI.IOI_QTY, 0) END AS NUMBER(38,4)) AS DEMAND_AS_SUBMITTED,
    CAST(O.PRIVATE_ALLOC AS NUMBER(38,4)) AS ORDER_ALLOCATION,
    CAST(NVL(NVL(NVL(TT.PRICING_TS, II.PRICING_DT), II.OFFER_DT), TT.TRADE_DATE) AS TIMESTAMP(3)) AS PRICING_TS,
    NVL(T.CURRENCY_CODE, II.CCY_CD) AS CURRENCY,
    REGEXP_REPLACE(T.SYNDICATE_DEAL_NAME, '\s*\(\s*([^)]*TRANCHE[^)]*|COMMON|[^)]*CONVERT[^)]*|BLOCK TRADE|NEW|PIPE|SERIES [A-Z0-9]+)\s*\)\s*$', '', 1, 0, 'i') AS ISSUER_NAME,
    T.ISSUER_INDUSTRY_SECTOR AS SECTOR,
    CAST(NVL(NVL(RT.TRN_UW_SIZE_QTY, RT.ACTIVE_TRANCHE_SIZE_QTY), 0) AS NUMBER(38,4)) AS TRANCHE_SIZE,
    NVL(EB.EXTERNAL_BROKER_NAME,
        CASE WHEN REGEXP_LIKE(RO.BILLED_BY_BRK_CD, '^CITI(BANK|GROUP|USA|US[0-9]+|UKE|BRAS|CAN|ASIA|AUS|SEC|INVS|G[A-Z]*|[0-9]+)?$', 'i')
             THEN 'Citigroup (' || RO.BILLED_BY_BRK_CD || ')' ELSE RO.BILLED_BY_BRK_CD END) AS BILLED_BY,
    T.PRODUCT_OFFERING_TYPE_VALUE AS OFFERING_TYPE,
    T.PRODUCT_EQUITY_TYPE_VALUE AS EQUITY_TYPE,
    CAST(NULL AS VARCHAR2(20)) AS ORDER_OWNERSHIP,
    O.DEAL_ID AS TRANSACTION_ID,
    O.INVESTOR_SALESPERSON_NAME AS SALES_PERSON,
    CAST(NULL AS VARCHAR2(400)) AS INVESTOR_LEI,
    O.ORDER_STATUS AS ORDER_STATUS,
    CAST(NULL AS VARCHAR2(400)) AS INVESTOR_QIB_STATUS,
    CAST(NULL AS VARCHAR2(500)) AS INVESTOR_SUB_TYPE,
    CAST(NULL AS VARCHAR2(10)) AS IS_FIRM_ORDER,
    CAST(NULL AS VARCHAR2(10)) AS IS_POT,
    CAST(NULL AS VARCHAR2(50)) AS DRAFT_ALLOC,
    CAST(NULL AS VARCHAR2(400)) AS SOFT_ALLOC,
    CAST(NULL AS VARCHAR2(400)) AS ISN_ALLOC,
    CAST(NULL AS VARCHAR2(400)) AS RETENTION,
    CAST(NULL AS VARCHAR2(4000)) AS RATIONALE,
    CAST(NULL AS VARCHAR2(400)) AS RATIONALE_TYPE,
    CAST(NULL AS VARCHAR2(400)) AS FX_CURRENCY,
    CAST(NULL AS VARCHAR2(500)) AS OBO_NAME,
    CAST(NULL AS VARCHAR2(400)) AS OBO_LEGAL_ENTITY_ID,
    CAST(NULL AS VARCHAR2(400)) AS ESG_TAG,
    CAST(NULL AS NUMBER(38,4)) AS ORDER_SIZE_CHANGE,
    CAST(NULL AS VARCHAR2(400)) AS IS_AFFILIATED,
    CAST(NULL AS VARCHAR2(400)) AS ONE_OFF_INVESTOR,
    CAST(NULL AS VARCHAR2(50)) AS SALES_SOEID,
    CAST(NULL AS VARCHAR2(1020)) AS WALL_CROSSED,
    CAST(NULL AS VARCHAR2(255)) AS INVESTOR_CLASSIFICATION,
    CAST(NULL AS VARCHAR2(1020)) AS EXISTING_HOLDER,
    CAST(NULL AS NUMBER(38,6)) AS ACTIVE_PRICE,
    CAST(NULL AS VARCHAR2(240)) AS BOOK_STATUS,
    CAST(NULL AS VARCHAR2(10)) AS DEAL_REGION,
    CAST(NULL AS VARCHAR2(1000)) AS TRANCHE_REGION,
    S.STATUS_VALUE AS DEAL_STATUS,
    CAST(T.DEAL_SIZE AS NUMBER(38,4)) AS DEAL_SIZE,
    CAST(NULL AS VARCHAR2(1100)) AS USE_OF_PROCEEDS,
    CAST(NVL(TT.SETTLEMENT_TS, II.SETTLEMENT_DT) AS TIMESTAMP(6)) AS SETTLEMENT_TS,
    CAST(NULL AS VARCHAR2(4000)) AS TENORS,
    CAST(NULL AS VARCHAR2(4000)) AS PRODUCT_CLASS,
    CAST(NULL AS VARCHAR2(4000)) AS DEAL_CLASS,
    LM.LIMIT_TYPE AS LIMIT_TYPE,
    CAST(LM.LIMIT_VALUE AS NUMBER(38,6)) AS LIMIT_VALUE,
    CAST(LM.LIMIT_COUPON AS NUMBER(38,6)) AS LIMIT_COUPON,
    CAST(LM.LIMIT_PREMIUM AS NUMBER(38,6)) AS LIMIT_PREMIUM,
    CAST(NULL AS VARCHAR2(400)) AS LIMIT_CURRENCY,
    CASE WHEN LV.IOI_LEVELS IS NOT NULL
         THEN CASE UPPER(O.IOI_UNIT) WHEN 'CURRENCY' THEN 'amounts: '
                                     WHEN 'PERCENT' THEN '% of deal: '
                                     WHEN 'FACE' THEN 'face: '
                                     ELSE '' END || LV.IOI_LEVELS END AS IOI_LEVELS,
    CAST(NULL AS VARCHAR2(400)) AS ORDER_SOURCE,
    CAST(CASE WHEN UPPER(O.IOI_UNIT) = 'SHARES' AND LM.LIMIT_VALUE IS NOT NULL
              THEN LM.IOI_QTY * LM.LIMIT_VALUE END AS NUMBER(38,4)) AS INDICATION_USD
FROM (
    SELECT E.*
    FROM (
        SELECT EO.ORDER_ID, EO.DEAL_ID, EO.TRANCHE_ID, EO.INVESTOR_NAME, EO.INVESTOR_GPNUM,
               EO.PRIVATE_ALLOC, EO.IOI_UNIT, EO.IOI_TYPE, EO.INVESTOR_SALESPERSON_NAME,
               EO.ORDER_STATUS,
               ROW_NUMBER() OVER (PARTITION BY EO.DEAL_ID, EO.TRANCHE_ID, EO.ORDER_ID
                                  ORDER BY EO.ROWID) AS RN_
        FROM DGSTREAM.IPREO_OB_ECM_ORDER EO
        WHERE EO.ORDER_ID IS NOT NULL
    ) E
    WHERE E.RN_ = 1
) O
INNER JOIN (
    SELECT X.*
    FROM (
        SELECT ET.ECM_TRANSACTION_ID, ET.DEAL_TRANSACTION_ID,
               ET.SYNDICATE_DEAL_NAME, ET.ISSUER_INDUSTRY_SECTOR,
               ET.PRODUCT_OFFERING_TYPE_VALUE, ET.PRODUCT_EQUITY_TYPE_VALUE,
               ET.DEAL_SIZE, ET.CURRENCY_CODE,
               ROW_NUMBER() OVER (PARTITION BY ET.DEAL_TRANSACTION_ID, ET.ECM_TRANSACTION_ID
                                  ORDER BY ET.ROWID) AS RN_
        FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION ET
    ) X
    WHERE X.RN_ = 1
) T
    ON O.DEAL_ID = T.DEAL_TRANSACTION_ID
    AND (O.ORDER_STATUS IS NULL OR O.ORDER_STATUS NOT IN ('CANCELLED', 'DELETED', 'PASS'))
INNER JOIN (
    SELECT ECM_TRANSACTION_ID,
           MAX(STATUS_VALUE) AS STATUS_VALUE
    FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION_STATUS
    WHERE STATUS_TYPE = 'Execution_Status'
      AND STATUS_VALUE NOT IN ('Confidential', 'Withdrawn', 'Terminated')
    GROUP BY ECM_TRANSACTION_ID
) S
    ON T.ECM_TRANSACTION_ID = S.ECM_TRANSACTION_ID
LEFT JOIN (
    SELECT ORDER_ID, MAX(LIMIT_VALUE) AS LIMIT_VALUE,
           MAX(IOI_QTY) AS IOI_QTY
    FROM DGSTREAM.IPREO_OB_ECM_ORDER_IOI
    GROUP BY ORDER_ID
) OI
    ON O.ORDER_ID = OI.ORDER_ID
LEFT JOIN (
    SELECT L.ORDER_ID, L.IOI_QTY, L.LIMIT_TYPE, L.LIMIT_VALUE, L.LIMIT_COUPON, L.LIMIT_PREMIUM
    FROM (
        SELECT I.ORDER_ID, I.IOI_QTY, I.LIMIT_TYPE, I.LIMIT_VALUE, I.LIMIT_COUPON, I.LIMIT_PREMIUM,
               ROW_NUMBER() OVER (PARTITION BY I.ORDER_ID
                                  ORDER BY I.IOI_QTY DESC NULLS LAST, I.ROWID) AS RN_
        FROM DGSTREAM.IPREO_OB_ECM_ORDER_IOI I
    ) L
    WHERE L.RN_ = 1
) LM
    ON LM.ORDER_ID = O.ORDER_ID
LEFT JOIN (
    SELECT V.ORDER_ID,
           CASE WHEN COUNT(*) > 1 THEN
             LISTAGG(RTRIM(TO_CHAR(V.IOI_QTY, 'FM999,999,999,999,999,999,990.9999'), '.') ||
                     CASE WHEN V.LIMIT_VALUE IS NOT NULL
                          THEN ' @ ' || TRIM(TO_CHAR(V.LIMIT_VALUE, '999,999,999,999,999,990.00'))
                          WHEN V.LIMIT_COUPON IS NOT NULL OR V.LIMIT_PREMIUM IS NOT NULL
                          THEN ' @ coupon ' || TRIM(TO_CHAR(V.LIMIT_COUPON, '990.0999')) ||
                               '% / premium ' || TRIM(TO_CHAR(V.LIMIT_PREMIUM, '990.0999')) || '%'
                          ELSE ' @ market' END,
                     ' | ' ON OVERFLOW TRUNCATE '...' WITH COUNT)
               WITHIN GROUP (ORDER BY CASE WHEN V.LIMIT_VALUE IS NULL AND V.LIMIT_COUPON IS NULL
                                            AND V.LIMIT_PREMIUM IS NULL THEN 0 ELSE 1 END,
                                       V.LIMIT_VALUE DESC NULLS LAST, V.IOI_QTY)
           END AS IOI_LEVELS
    FROM (
        SELECT DISTINCT I.ORDER_ID, I.IOI_QTY, I.LIMIT_VALUE, I.LIMIT_COUPON, I.LIMIT_PREMIUM
        FROM DGSTREAM.IPREO_OB_ECM_ORDER_IOI I
        WHERE I.IOI_QTY IS NOT NULL
    ) V
    GROUP BY V.ORDER_ID
) LV
    ON LV.ORDER_ID = O.ORDER_ID
LEFT JOIN (
    SELECT W.*
    FROM (
        SELECT TTR.ECM_TRANSACTION_ID, TTR.ECM_TRANSACTION_TRANCHE_ID,
               TTR.PRICING_TS, TTR.SETTLEMENT_TS, TTR.TRADE_DATE,
               ROW_NUMBER() OVER (PARTITION BY TTR.ECM_TRANSACTION_ID,
                                               TTR.ECM_TRANSACTION_TRANCHE_ID
                                  ORDER BY TTR.ROWID) AS RN_
        FROM DGSTREAM.IPREO_OPUS_ECM_TRANSACTION_TRANCHE TTR
    ) W
    WHERE W.RN_ = 1
) TT
    ON T.ECM_TRANSACTION_ID = TT.ECM_TRANSACTION_ID
    AND TO_CHAR(TT.ECM_TRANSACTION_TRANCHE_ID) = O.TRANCHE_ID
LEFT JOIN (
    SELECT V.*
    FROM (
        SELECT R.TRN_ID, R.TRN_NM, R.ACTIVE_TRANCHE_SIZE_QTY, R.TRN_UW_SIZE_QTY, R.OVERALLOTMENT_QTY,
               ROW_NUMBER() OVER (PARTITION BY R.TRN_ID ORDER BY R.ROWID) AS RN_
