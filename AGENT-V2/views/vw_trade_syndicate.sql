CREATE OR REPLACE VIEW "DGSTREAM"."VW_TRADE_SYNDICATE" AS
SELECT
    'DCM' AS PRODUCT,
    S.ORDER_TRADE_ID AS TRADE_ID,
    S.DEALER AS DEALER,
    CAST(S.DESIGNATION_AMT AS NUMBER(38,4)) AS DESIGNATION_AMT,
    CAST(S.ADJUSTED_DESIGNATION_AMT AS NUMBER(38,4)) AS ADJUSTED_DESIGNATION_AMT,
    CAST(S.ADJUSTED_DESIGNATION_PCT AS NUMBER(38,9)) AS ADJUSTED_DESIGNATION_PCT,
    CAST(S.CARVEOUT_AMT AS NUMBER(38,4)) AS CARVEOUT_AMT,
    CAST(S.DISTRIBUTED_CARVEOUT AS NUMBER(38,4)) AS DISTRIBUTED_CARVEOUT
FROM (
    SELECT W.*
    FROM (
        SELECT TS.*,
               ROW_NUMBER() OVER (PARTITION BY TS.ORDER_TRADE_ID, TS.DEALER
                                  ORDER BY TS.DG_UPDATED_TS DESC NULLS LAST,
                                           TS.ROWID) AS RN_
        FROM DGSTREAM.OB_ORDER_TRADE_SYNDICATE TS
        WHERE TS.ORDER_TRADE_ID IS NOT NULL
    ) W
    WHERE W.RN_ = 1
) S
;
